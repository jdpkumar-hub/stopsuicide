export function expandSearchQuery(query: string) {
  const q = unicodeNormalize(query.trim());
  const expanded = new Set<string>(q ? [q] : []);
  if (!q) return [];
  Object.entries(SEARCH_SYNONYMS).forEach(([term, aliases]) => {
    const hay = [term, ...aliases].map(unicodeNormalize);
    if (hay.some((item) => item.includes(q) || q.includes(item))) {
      hay.forEach((item) => expanded.add(item));
    }
  });
  return [...expanded];
}
